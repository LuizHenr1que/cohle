// Admin API: roles, permissions, metrics. Dev server started with OWNER_EMAILS=teste1@cohle.dev (teste1 = master, teste2 = regular).
import { io } from "../bots/node_modules/socket.io-client/build/esm/index.js";
const API = process.env.API ?? "http://localhost:3001";
let pass = 0, fail = 0; const ok = (l, c, x = "") => { c ? pass++ : fail++; console.log(`${c ? "PASS" : "FAIL"}  ${l}${x ? "  — " + x : ""}`); };
const http = async (p, b, tok, m) => { const r = await fetch(API + p, { method: m ?? (b ? "POST" : "GET"), headers: { ...(b ? { "Content-Type": "application/json" } : {}), ...(tok ? { Authorization: "Bearer " + tok } : {}) }, body: b ? JSON.stringify(b) : undefined }); return { s: r.status, d: await r.json().catch(() => ({})) }; };
const login = async (e) => (await http("/auth/login", { email: e, password: "teste12345" })).d;
const a = await login("teste1@cohle.dev"), b = await login("teste2@cohle.dev");
ok("o dono entra com papel OWNER", a.user.role === "OWNER", String(a.user.role));
ok("pessoa comum não recebe papel", b.user.role === undefined);
ok("/me do dono diz OWNER", (await http("/me", null, a.token)).d.role === "OWNER");
for (const p of ["/admin/overview", "/admin/users", "/admin/accesses", "/admin/series", "/admin/usage"]) ok(`pessoa comum recebe 403 em ${p}`, (await http(p, null, b.token)).s === 403);
ok("sem login recebe 401", (await http("/admin/overview")).s === 401);
const sock = io(API, { auth: { token: a.token }, transports: ["websocket"] }); await new Promise((r) => sock.on("connect", r));
const ov = await http("/admin/overview", null, a.token);
ok("overview responde", ov.s === 200 && ov.d.users.total >= 2, JSON.stringify(ov.d.users));
ok("conta o dono online ao vivo", ov.d.live.online >= 1);
ok("memória e banco medidos", ov.d.process.rssMb > 20 && ov.d.dbMb > 1, `${ov.d.process.rssMb} MB / banco ${ov.d.dbMb} MB`);
const us = await http("/admin/users?q=teste2", null, a.token);
ok("busca por nome/e-mail", us.d.rows.length === 1 && us.d.rows[0].email === "teste2@cohle.dev");
ok("a lista nunca expõe senha", !JSON.stringify(us.d).includes("passwordHash") && !JSON.stringify(us.d).includes("argon2"));
const ac = await http("/admin/accesses", null, a.token);
ok("acessos recentes registram o login", ac.d.some((r) => r.kind === "login" && r.email === "teste1@cohle.dev"));
const se = await http("/admin/series?range=24h", null, a.token);
ok("série diária cobre 30 dias", se.d.days.length === 30 && se.d.days.at(-1).login >= 1);
const ug = await http("/admin/usage", null, a.token);
ok("4 cotas do plano grátis", ug.d.quotas.length === 4 && ug.d.quotas.every((q) => q.limit > 0 && ["ok", "warn", "over"].includes(q.level)), ug.d.quotas.map((q) => `${q.id}=${q.used}/${q.limit}`).join(" "));
// roles
ok("só o dono muda papéis (comum não)", (await http(`/admin/users/${a.user.id}/role`, { role: "USER" }, b.token)).s === 403);
ok("o dono não pode ser rebaixado", (await http(`/admin/users/${a.user.id}/role`, { role: "USER" }, a.token)).s === 400);
let r = await http(`/admin/users/${b.user.id}/role`, { role: "ADMIN" }, a.token);
ok("dono promove a admin", r.s === 200);
const b2 = await login("teste2@cohle.dev");
ok("admin entra com papel ADMIN", b2.user.role === "ADMIN");
ok("admin vê o painel", (await http("/admin/overview", null, b2.token)).s === 200);
ok("admin NÃO muda papéis", (await http(`/admin/users/${a.user.id}/role`, { role: "USER" }, b2.token)).s === 403);
r = await http(`/admin/users/${b.user.id}/role`, { role: "USER" }, a.token);
ok("dono rebaixa de volta", r.s === 200 && (await http("/admin/overview", null, b2.token)).s === 403);
sock.close();
console.log(`\n${pass} passaram, ${fail} falharam`); process.exit(fail ? 1 : 0);
